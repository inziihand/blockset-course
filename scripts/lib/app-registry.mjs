const normalize = (value) => `${JSON.stringify(value, null, 2)}\n`;

function loaderName(appKey) {
  return `load${appKey.split('-').map((part) => `${part[0].toUpperCase()}${part.slice(1)}`).join('')}`;
}

function quote(value) {
  return JSON.stringify(value);
}

export function generateAppRegistrySource(manifests) {
  const apps = manifests.filter((app) => app.kind === 'frontend-app')
    .sort((left, right) => left.frontend.order - right.frontend.order || left.appKey.localeCompare(right.appKey));
  const icons = [...new Set(apps.map((app) => app.frontend.icon))].sort();
  const lines = [
    '// Generated by scripts/generate-app-registry.mjs. Do not edit directly.',
    `import { ${icons.join(', ')} } from 'lucide-react';`,
    "import type { ShellAppDefinition } from './types';",
    '',
  ];
  for (const app of apps) {
    const sourcePrefix = 'apps/console/src/apps/';
    if (!app.source.startsWith(sourcePrefix) || app.source.includes('..') || app.frontend.entryModule.includes('..')) {
      throw new Error(`Frontend App has an unsafe Registry source: ${app.appKey}`);
    }
    const relativeSource = app.source.slice(sourcePrefix.length);
    const entry = app.frontend.entryModule.replace(/\.tsx$/, '');
    lines.push(`const ${loaderName(app.appKey)} = () => import('../apps/${relativeSource}/${entry}');`);
  }
  lines.push('', 'export const generatedAppRegistry: readonly ShellAppDefinition[] = [');
  for (const app of apps) {
    const frontend = app.frontend;
    lines.push('  {');
    lines.push(`    key: ${quote(app.appKey)},`);
    lines.push(`    version: ${quote(app.version)},`);
    lines.push(`    path: ${quote(`/apps/${app.appKey}`)},`);
    lines.push(`    title: ${quote(frontend.title)},`);
    lines.push(`    subtitle: ${quote(frontend.subtitle)},`);
    lines.push(`    description: ${quote(frontend.description)},`);
    lines.push(`    icon: ${frontend.icon},`);
    lines.push(`    status: ${quote(frontend.status)},`);
    lines.push(`    displayMode: ${quote(frontend.displayMode)},`);
    if (frontend.headerLayout) lines.push(`    headerLayout: ${quote(frontend.headerLayout)},`);
    if (frontend.keepAlive !== undefined) {
      if (typeof frontend.keepAlive !== 'boolean') throw new Error(`Invalid App keepAlive policy: ${app.appKey}`);
      lines.push(`    keepAlive: ${frontend.keepAlive},`);
    }
    lines.push(`    load: ${loaderName(app.appKey)},`);
    lines.push(`    access: ${quote(app.access.defaultMode === 'public' ? 'public' : 'identity')},`);
    if (app.requiredServices.length === 0 && app.lifecycle.category !== 'core'
      && !app.access.protected && app.package?.installable === true) {
      lines.push(`    sourceActivation: ${quote({
        displayName: app.displayName,
        category: app.lifecycle.category,
        removable: app.lifecycle.removable,
        protected: false,
        defaultAccessMode: app.access.defaultMode,
        allowedAccessModes: app.access.allowedModes,
        entitlements: app.access.entitlements ?? [],
        adminAllowed: app.access.adminAllowed,
      })},`);
    }
    lines.push('  },');
  }
  lines.push('];', '');
  return lines.join('\n');
}
